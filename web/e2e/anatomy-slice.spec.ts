import {test,expect} from '@playwright/test';
import {installLocalNetworkGuard} from '../scripts/local-network-guard.mjs';
import {readMPRStats} from '../scripts/render-stats.mjs';

test('anatomy slice starts on its native plane, shows cloud evidence and remains separate through adoption',async({page,context})=>{
  await installLocalNetworkGuard(context,'http://127.0.0.1:5174');
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');await page.getByLabel('Логин',{exact:true}).fill('cloud-slice-resident');await page.getByLabel('Пароль',{exact:true}).fill(process.env.HEART3D_E2E_PASSWORD!);await page.getByRole('button',{name:'Войти в рабочее пространство'}).click();
  await page.getByRole('button',{name:'Открыть разметку'}).click();await expect(page.getByText('● Геометрия проверена')).toBeVisible({timeout:45000});
  let project=(await (await page.request.get('/api/projects')).json())[0];const id=project.id;
  const candidate=project.predictions.find((p:any)=>p.provenance.variant==='anatomy_slice_draft');
  expect(project.predictions.some((p:any)=>p.provenance.variant==='slice_draft')).toBe(true);
  expect(candidate.source).toBe('AI anatomy slice draft');expect(candidate.approved).toBe(false);
  await expect(page.getByLabel('Показать маску')).toHaveValue(candidate.id);
  await expect(page.getByLabel('Срез Аксиальная',{exact:true})).toHaveValue('31');
  await expect(page.locator('.pane-0 .pane-label small')).toHaveText('32 / 64');
  await expect(page.locator('.slice-scope')).toContainText('Анатомический AI-черновик');
  await expect(page.locator('.slice-scope')).toContainText('Визуальные наблюдения: облачная модель');
  await expect(page.getByRole('button',{name:'3D-реконструкция'})).toBeDisabled();
  await expect(page.getByRole('button',{name:'Кисть',exact:true})).toBeDisabled();
  await expect.poll(async()=> (await readMPRStats(page))[0].colored).toBeGreaterThan(20);
  const immutableBefore=await (await page.request.get(`/api/projects/${id}/export/${candidate.id}`)).body();
  await page.getByRole('button',{name:'Анатомический разбор CT',exact:true}).click();
  const panel=page.getByRole('complementary',{name:'Анатомический разбор CT'});
  await expect(panel).toBeVisible();await expect(panel.locator('.anatomy-notes article')).toHaveCount(3);
  await expect(panel.locator('.anatomy-notes article').first()).toContainText('Облачная модель');
  await expect(panel.locator('.anatomy-notes').getByRole('button',{name:'Изменить',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Закрыть анатомический разбор',exact:true}).click();
  await page.getByLabel('Показать маску').selectOption(candidate.id);
  const candidateMask=await (await page.request.get(`/api/projects/${id}/mask?version_id=${candidate.id}`)).body();
  await page.getByRole('button',{name:'Редактировать границы',exact:true}).click();
  await expect(page.getByRole('button',{name:'Кисть',exact:true})).toBeEnabled();
  await expect(page.getByTestId('contour-count')).toHaveText('1');
  expect((await (await page.request.get(`/api/projects/${id}/mask`)).body()).equals(candidateMask)).toBe(true);
  await expect(page.locator('.slice-scope')).toContainText('Черновик для проверки на основе анатомического AI-разбора');
  project=await (await page.request.get('/api/projects/'+id)).json();
  expect(project.version_id).not.toBe(candidate.id);expect(project.document.base_prediction_id).toBe(candidate.id);
  expect(project.annotation_scope).toEqual({axis:2,index:31,complete_volume:false});expect(project.status).toBe('in_progress');
  expect((await (await page.request.get(`/api/projects/${id}/export/${candidate.id}`)).body()).equals(immutableBefore)).toBe(true);
  expect((await (await page.request.get(`/api/projects/${id}/anatomy-review`)).json()).version_id).toBe(candidate.provenance.notebook_version_id);
  await page.getByTestId('contour-item').first().click();
  const handle=page.getByTestId('viewport-0').locator('svg circle').first();await expect(handle).toBeVisible();
  const box=(await handle.boundingBox())!;await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();await page.mouse.move(box.x+box.width/2-14,box.y+box.height/2+8,{steps:8});await page.mouse.up();
  await expect.poll(async()=> (await (await page.request.get('/api/projects/'+id)).json()).version_id).not.toBe(project.version_id);
  expect((await (await page.request.get(`/api/projects/${id}/mask`)).body()).equals(candidateMask)).toBe(false);
  expect((await (await page.request.get(`/api/projects/${id}/export/${candidate.id}`)).body()).equals(immutableBefore)).toBe(true);
  await page.reload();await expect(page.getByText('● Геометрия проверена')).toBeVisible({timeout:45000});await expect(page.getByTestId('contour-count')).toHaveText('1');
  expect(errors).toEqual([]);
});
